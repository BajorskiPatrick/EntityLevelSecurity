package com.els.jdbc;

import com.els.context.AclContext;
import com.els.logger.Logger;
import com.els.parser.SqlRewriter;

import java.sql.*;

/**
 * Proxy dla Statement, które przechwytuje i modyfikuje zapytania SQL.
 *
 * W przeciwieństwie do PreparedStatement, Statement przyjmuje SQL w metodach execute*(),
 * więc modyfikacja musi nastąpić w tych metodach, a nie w createStatement().
 */
public class AclStatementProxy implements Statement {

    private final Statement delegate;
    private final SqlRewriter rewriter = new SqlRewriter();
    private final Logger logger = Logger.getInstance();

    public AclStatementProxy(Statement delegate) {
        this.delegate = delegate;
    }

    /**
     * Przechwytuje SELECT queries i dodaje ACL filtering.
     */
    @Override
    public ResultSet executeQuery(String sql) throws SQLException {
        if (AclContext.isActive()) {
            String modifiedSql = rewriter.addAclToSql(sql, AclContext.getCurrentUser());
            logger.log("Statement.executeQuery() - Rewritten SQL: " + modifiedSql);
            return delegate.executeQuery(modifiedSql);
        }
        return delegate.executeQuery(sql);
    }

    /**
     * Przechwytuje UPDATE/DELETE queries i dodaje ACL filtering.
     * Zapobiega modyfikacji rekordów, do których użytkownik nie ma dostępu.
     */
    @Override
    public int executeUpdate(String sql) throws SQLException {
        if (AclContext.isActive()) {
            String modifiedSql = rewriter.addAclToSql(sql, AclContext.getCurrentUser());
            logger.log("Statement.executeUpdate() - Rewritten SQL: " + modifiedSql);
            return delegate.executeUpdate(modifiedSql);
        }
        return delegate.executeUpdate(sql);
    }

    /**
     * Przechwytuje dowolne SQL (SELECT/INSERT/UPDATE/DELETE/DDL).
     */
    @Override
    public boolean execute(String sql) throws SQLException {
        if (AclContext.isActive()) {
            String modifiedSql = rewriter.addAclToSql(sql, AclContext.getCurrentUser());
            logger.log("Statement.execute() - Rewritten SQL: " + modifiedSql);
            return delegate.execute(modifiedSql);
        }
        return delegate.execute(sql);
    }

    // Wersje z autoGeneratedKeys

    @Override
    public int executeUpdate(String sql, int autoGeneratedKeys) throws SQLException {
        if (AclContext.isActive()) {
            String modifiedSql = rewriter.addAclToSql(sql, AclContext.getCurrentUser());
            logger.log("Statement.executeUpdate(keys) - Rewritten SQL: " + modifiedSql);
            return delegate.executeUpdate(modifiedSql, autoGeneratedKeys);
        }
        return delegate.executeUpdate(sql, autoGeneratedKeys);
    }

    @Override
    public int executeUpdate(String sql, int[] columnIndexes) throws SQLException {
        if (AclContext.isActive()) {
            String modifiedSql = rewriter.addAclToSql(sql, AclContext.getCurrentUser());
            logger.log("Statement.executeUpdate(indexes) - Rewritten SQL: " + modifiedSql);
            return delegate.executeUpdate(modifiedSql, columnIndexes);
        }
        return delegate.executeUpdate(sql, columnIndexes);
    }

    @Override
    public int executeUpdate(String sql, String[] columnNames) throws SQLException {
        if (AclContext.isActive()) {
            String modifiedSql = rewriter.addAclToSql(sql, AclContext.getCurrentUser());
            logger.log("Statement.executeUpdate(names) - Rewritten SQL: " + modifiedSql);
            return delegate.executeUpdate(modifiedSql, columnNames);
        }
        return delegate.executeUpdate(sql, columnNames);
    }

    @Override
    public boolean execute(String sql, int autoGeneratedKeys) throws SQLException {
        if (AclContext.isActive()) {
            String modifiedSql = rewriter.addAclToSql(sql, AclContext.getCurrentUser());
            logger.log("Statement.execute(keys) - Rewritten SQL: " + modifiedSql);
            return delegate.execute(modifiedSql, autoGeneratedKeys);
        }
        return delegate.execute(sql, autoGeneratedKeys);
    }

    @Override
    public boolean execute(String sql, int[] columnIndexes) throws SQLException {
        if (AclContext.isActive()) {
            String modifiedSql = rewriter.addAclToSql(sql, AclContext.getCurrentUser());
            logger.log("Statement.execute(indexes) - Rewritten SQL: " + modifiedSql);
            return delegate.execute(modifiedSql, columnIndexes);
        }
        return delegate.execute(sql, columnIndexes);
    }

    @Override
    public boolean execute(String sql, String[] columnNames) throws SQLException {
        if (AclContext.isActive()) {
            String modifiedSql = rewriter.addAclToSql(sql, AclContext.getCurrentUser());
            logger.log("Statement.execute(names) - Rewritten SQL: " + modifiedSql);
            return delegate.execute(modifiedSql, columnNames);
        }
        return delegate.execute(sql, columnNames);
    }

    // Batch operations - wykonywane na już dodanych komendach

    @Override
    public void addBatch(String sql) throws SQLException {
        if (AclContext.isActive()) {
            String modifiedSql = rewriter.addAclToSql(sql, AclContext.getCurrentUser());
            logger.log("Statement.addBatch() - Rewritten SQL: " + modifiedSql);
            delegate.addBatch(modifiedSql);
        } else {
            delegate.addBatch(sql);
        }
    }

    @Override
    public int[] executeBatch() throws SQLException {
        // Komendy batch są już zmodyfikowane w addBatch()
        return delegate.executeBatch();
    }

    @Override
    public void clearBatch() throws SQLException {
        delegate.clearBatch();
    }

    // ========================================
    // Pozostałe metody - delegacja bez zmian
    // ========================================

    @Override
    public void close() throws SQLException {
        delegate.close();
    }

    @Override
    public int getMaxFieldSize() throws SQLException {
        return delegate.getMaxFieldSize();
    }

    @Override
    public void setMaxFieldSize(int max) throws SQLException {
        delegate.setMaxFieldSize(max);
    }

    @Override
    public int getMaxRows() throws SQLException {
        return delegate.getMaxRows();
    }

    @Override
    public void setMaxRows(int max) throws SQLException {
        delegate.setMaxRows(max);
    }

    @Override
    public void setEscapeProcessing(boolean enable) throws SQLException {
        delegate.setEscapeProcessing(enable);
    }

    @Override
    public int getQueryTimeout() throws SQLException {
        return delegate.getQueryTimeout();
    }

    @Override
    public void setQueryTimeout(int seconds) throws SQLException {
        delegate.setQueryTimeout(seconds);
    }

    @Override
    public void cancel() throws SQLException {
        delegate.cancel();
    }

    @Override
    public SQLWarning getWarnings() throws SQLException {
        return delegate.getWarnings();
    }

    @Override
    public void clearWarnings() throws SQLException {
        delegate.clearWarnings();
    }

    @Override
    public void setCursorName(String name) throws SQLException {
        delegate.setCursorName(name);
    }

    @Override
    public ResultSet getResultSet() throws SQLException {
        return delegate.getResultSet();
    }

    @Override
    public int getUpdateCount() throws SQLException {
        return delegate.getUpdateCount();
    }

    @Override
    public boolean getMoreResults() throws SQLException {
        return delegate.getMoreResults();
    }

    @Override
    public void setFetchDirection(int direction) throws SQLException {
        delegate.setFetchDirection(direction);
    }

    @Override
    public int getFetchDirection() throws SQLException {
        return delegate.getFetchDirection();
    }

    @Override
    public void setFetchSize(int rows) throws SQLException {
        delegate.setFetchSize(rows);
    }

    @Override
    public int getFetchSize() throws SQLException {
        return delegate.getFetchSize();
    }

    @Override
    public int getResultSetConcurrency() throws SQLException {
        return delegate.getResultSetConcurrency();
    }

    @Override
    public int getResultSetType() throws SQLException {
        return delegate.getResultSetType();
    }

    @Override
    public Connection getConnection() throws SQLException {
        return delegate.getConnection();
    }

    @Override
    public boolean getMoreResults(int current) throws SQLException {
        return delegate.getMoreResults(current);
    }

    @Override
    public ResultSet getGeneratedKeys() throws SQLException {
        return delegate.getGeneratedKeys();
    }

    @Override
    public int getResultSetHoldability() throws SQLException {
        return delegate.getResultSetHoldability();
    }

    @Override
    public boolean isClosed() throws SQLException {
        return delegate.isClosed();
    }

    @Override
    public void setPoolable(boolean poolable) throws SQLException {
        delegate.setPoolable(poolable);
    }

    @Override
    public boolean isPoolable() throws SQLException {
        return delegate.isPoolable();
    }

    @Override
    public void closeOnCompletion() throws SQLException {
        delegate.closeOnCompletion();
    }

    @Override
    public boolean isCloseOnCompletion() throws SQLException {
        return delegate.isCloseOnCompletion();
    }

    @Override
    public <T> T unwrap(Class<T> iface) throws SQLException {
        return delegate.unwrap(iface);
    }

    @Override
    public boolean isWrapperFor(Class<?> iface) throws SQLException {
        return delegate.isWrapperFor(iface);
    }
}

